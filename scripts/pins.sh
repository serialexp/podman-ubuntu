#!/usr/bin/env bash
# Prints the rsansible variables that pin one release's packages: the asset
# URL and SHA-256 of every .deb, per Ubuntu release. Gothab release assets
# have no by-name URL, so hosts pin these until the packages are in an apt
# repository.
#
#   scripts/pins.sh v6.1.4-1 > vars/podman.yml
set -euo pipefail
tag=${1:?usage: pins.sh <tag>}
repo=serialexp/podman-ubuntu
base=https://gothab.io/api/v1/repos/$repo/releases

release=$(gt release view "$tag" -R "$repo" --json)
id=$(jq -r .id <<<"$release")

echo "# Generated by scripts/pins.sh $tag."
echo "podman_ubuntu_release: $tag"
echo "podman_ubuntu_packages:"
for sums in $(jq -r '.assets[].name | select(startswith("SHA256SUMS-ubuntu"))' <<<"$release" | sort); do
  ubuntu=${sums#SHA256SUMS-ubuntu}
  echo "  \"$ubuntu\":"
  asset=$(jq -r --arg n "$sums" '.assets[] | select(.name == $n) | .id' <<<"$release")
  while read -r sha name; do
    deb=$(jq -r --arg n "$name" '.assets[] | select(.name == $n) | .id' <<<"$release")
    [ -n "$deb" ] || { echo "$name is in $sums but not in the release" >&2; exit 1; }
    echo "    - name: ${name%%_*}"
    echo "      file: $name"
    echo "      url: \"$base/$id/assets/$deb\""
    echo "      sha256: $sha"
  done < <(curl -fsSL "$base/$id/assets/$asset")
done
